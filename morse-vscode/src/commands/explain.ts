/**
 * Explain command - explain selected code
 */

import * as vscode from 'vscode';
import { MorseClient } from '../morse/client';

export function registerExplainCommand(context: vscode.ExtensionContext, client: MorseClient): void {
    context.subscriptions.push(
        vscode.commands.registerCommand('morse.explain', async () => {
            const editor = vscode.window.activeTextEditor;
            if (!editor) {
                vscode.window.showWarningMessage('No active editor');
                return;
            }

            const document = editor.document;
            const selection = editor.selection;

            let code: string;
            let range: vscode.Range;

            if (selection.isEmpty) {
                const position = selection.active;
                const symbol = await findEnclosingSymbol(document, position);
                if (symbol) {
                    range = symbol.range;
                    code = document.getText(range);
                } else {
                    vscode.window.showWarningMessage('Please select code to explain');
                    return;
                }
            } else {
                range = new vscode.Range(selection.start, selection.end);
                code = document.getText(range);
            }

            const detailOption = await vscode.window.showQuickPick(
                [
                    { label: 'Brief', description: 'Quick overview', value: 'brief' as const },
                    { label: 'Normal', description: 'Standard explanation', value: 'normal' as const },
                    { label: 'Detailed', description: 'In-depth analysis', value: 'detailed' as const },
                ],
                { placeHolder: 'Select explanation detail level' }
            );

            if (!detailOption) {
                return;
            }

            await vscode.window.withProgress({
                location: vscode.ProgressLocation.Notification,
                title: 'Morse is analyzing your code...',
                cancellable: true,
            }, async (_progress, token) => {
                try {
                    const result = await client.explain({
                        code,
                        language: document.languageId,
                        detail: detailOption.value,
                        context: {
                            filePath: document.fileName,
                            selection: {
                                start: { line: range.start.line, character: range.start.character },
                                end: { line: range.end.line, character: range.end.character },
                            },
                        },
                    });

                    if (token.isCancellationRequested) {
                        return;
                    }

                    const markdown = formatExplanation(result.explanation, result.keyPoints, code, document.languageId);
                    const doc = await vscode.workspace.openTextDocument({
                        language: 'markdown',
                        content: markdown,
                    });

                    await vscode.window.showTextDocument(doc, {
                        viewColumn: vscode.ViewColumn.Beside,
                        preview: true,
                    });

                } catch (err) {
                    const message = err instanceof Error ? err.message : 'Unknown error';
                    vscode.window.showErrorMessage(`Explanation failed: ${message}`);
                }
            });
        })
    );
}

async function findEnclosingSymbol(document: vscode.TextDocument, position: vscode.Position): Promise<vscode.DocumentSymbol | undefined> {
    const symbols = await vscode.commands.executeCommand<vscode.DocumentSymbol[]>(
        'vscode.executeDocumentSymbolProvider',
        document.uri
    );

    if (!symbols) {
        return undefined;
    }

    function findSymbol(symbols: vscode.DocumentSymbol[]): vscode.DocumentSymbol | undefined {
        for (const symbol of symbols) {
            if (symbol.range.contains(position)) {
                const child = findSymbol(symbol.children);
                return child || symbol;
            }
        }
        return undefined;
    }

    return findSymbol(symbols);
}

function formatExplanation(explanation: string, keyPoints: string[], code: string, language: string): string {
    return `# Code Explanation\n\n## Overview\n\n${explanation}\n\n## Key Points\n\n${keyPoints.map(point => `- ${point}`).join('\n')}\n\n## Code\n\n\`\`\`${language}\n${code}\n\`\`\`\n\n---\n*Generated by Morse AI*\n`;
}
